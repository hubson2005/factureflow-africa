import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

export interface LayoutBlockPosition {
  x: number; // mm depuis la gauche de la page A4 (largeur 210mm)
  y: number; // mm depuis le haut de la page A4 (hauteur 297mm)
}

export interface LayoutBlocks {
  logo?: LayoutBlockPosition;
  company_info?: LayoutBlockPosition;
  items_table?: LayoutBlockPosition;
  totals?: LayoutBlockPosition;
  qr_code?: LayoutBlockPosition;
  signature?: LayoutBlockPosition;
}

export interface InvoiceTemplateConfig {
  theme?: string;
  primaryColor: string;   // hex, ex: "#f97316"
  secondaryColor: string; // hex
  accentColor: string;    // hex
  logoUrl?: string | null;
  fontFamily?: string;    // Arial | Roboto | Poppins | Open Sans | Inter (mappé vers une police jsPDF)
  headerLogoPosition?: "left" | "center" | "right";
  footerMentions?: string | null;
  footerConditions?: string | null;
  footerCoordonnees?: string | null;
  footerReseauxSociaux?: string | null;
  visibleColumns?: string[]; // ex: ["reference","description","quantity","unit","tva","remise","unit_price","total"]
  showSignature?: boolean;
  signatureUrl?: string | null;
  showQrCode?: boolean;
  qrCodeType?: "paiement" | "telechargement" | "verification";
  qrCodeValue?: string; // URL ou contenu à encoder, fourni par l'appelant selon qrCodeType
  watermarkEnabled?: boolean;
  language?: "fr" | "en" | "bilingue";
  currency?: string; // FCFA | XAF | USD | EUR
  useCustomLayout?: boolean;   // active le positionnement libre (glisser-déposer)
  layoutBlocks?: LayoutBlocks; // positions custom, utilisées seulement si useCustomLayout=true
}

export interface InvoicePDFItem {
  description: string;
  qty: number;
  unitPrice: number;
  reference?: string;
  unit?: string;      // ex: "pcs", "kg", "heure"
  discount?: number;  // pourcentage, ex: 10 pour 10%
  tvaRate?: number;   // taux TVA propre à la ligne, sinon tvaRate global est utilisé
}

export interface InvoicePDFData {
  code: string;
  issueDate: string;
  dueDate?: string;
  status: string; // "brouillon" | "payee" | "annulee" | "en_retard" | autre
  clientName: string;
  clientEmail?: string;
  clientPhone?: string;
  clientCity?: string;
  companyName?: string;
  companyPhone?: string;
  companyEmail?: string;
  companyAddress?: string;
  items: InvoicePDFItem[];
  notes?: string;
  tvaRate?: number;
  template?: InvoiceTemplateConfig;
}

const DEFAULT_TEMPLATE: InvoiceTemplateConfig = {
  primaryColor: "#f97316",
  secondaryColor: "#141a1a",
  accentColor: "#78827b",
  fontFamily: "Inter",
  headerLogoPosition: "left",
  visibleColumns: ["description", "quantity", "unit_price", "total"],
  language: "fr",
  currency: "FCFA",
};

